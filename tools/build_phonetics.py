def main():
    alpha = json.load(open(ROOT / 'assets/data/alphabet/th_alphabet.json', encoding='utf-8'))
    cons = {}
    for c in alpha['consonants']:
        ipa, fk = CONS[c['char']]
        roman, place, sim, diff = SOUND[ipa]
        cons[c['char']] = {'ipa': ipa, 'ipaFinal': FINAL_IPA[fk], 'roman': roman, 'romanFinal': '' if fk == '-' else fk.replace('ŋ', 'ng'),
                           'place': place, 'korSim': sim, 'korDiff': diff, 'final': FINAL_KO[fk], 'note': NOTE.get(c['char'], '')}
    vow = {}
    for v in alpha['vowels']:
        ipa = VOWELS[v['form']]
        base = ipa.rstrip('ː')
        if base in VD:
            roman, place, sim, diff = VD[base]
            x, y = V9[base]
            long_ = ipa.endswith('ː')
            if long_:
                diff = diff + ' 장모음 — 단모음보다 두 배쯤 길게 끈다(한국어는 길이로 뜻을 가르지 않으니 의식해서 늘인다).'
            LONG = {'a': 'aa', 'i': 'ii', 'ue': 'uee', 'u': 'uu', 'e': 'ee', 'ae': 'aae', 'o': 'oo', 'oe': 'oe'}
            if base == 'ɔ':
                roman = 'aw' if long_ else 'o'
            vow[v['form']] = {'ipa': ipa, 'roman': (LONG.get(roman, roman) if long_ and base != 'ɔ' else roman), 'place': place, 'korSim': sim, 'korDiff': diff, 'pos': [x, y], 'say': v['form'].replace('–', 'อ')}
        else:
            roman, place, sim, diff = COMPLEX[ipa]
            vow[v['form']] = {'ipa': ipa, 'roman': roman, 'place': place, 'korSim': sim, 'korDiff': diff, 'pos': None, 'say': v['form'].replace('–', 'อ')}
    out = {'_meta': '문자·발음 기초(자음 44·모음 25·성조 5) — 방콕 표준어, 자체 작성 · tools/build_phonetics.py', 'consonants': cons, 'vowels': vow, 'tones': TONES,
           'thaiVowelPos': V9, 'korVowels': KOR_VOWELS}
    json.dump(out, open(ROOT / 'assets/data/alphabet/th_phonetics.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print(len(cons), len(vow), len(TONES))


if __name__ == '__main__':
    main()
